// gen_data.js — rebuilds poc/data/honeycreeper_data.js from the three CSVs next to it.
//   node poc/data/gen_data.js
// Sources of truth: honeycreeper_nodes.csv (species), honeycreeper_edges.csv (nested tree), honeycreeper_pop.csv (population anchors).
const fs = require('fs');
const path = require('path');

function parseCSV(t) {
  t = t.replace(/^\uFEFF/, '');
  const rows = []; let row = [], cur = '', q = false;
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (q) { if (c === '"') { if (t[i + 1] === '"') { cur += '"'; i++; } else q = false; } else cur += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cur); cur = ''; }
    else if (c === '\n') { row.push(cur.replace(/\r$/, '')); rows.push(row); row = []; cur = ''; }
    else cur += c;
  }
  if (cur || row.length) { row.push(cur.replace(/\r$/, '')); rows.push(row); }
  const head = rows.shift();
  return rows.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((k, i) => [k, r[i]])));
}
const read = f => parseCSV(fs.readFileSync(path.join(__dirname, f), 'utf8'));

const nodes = read('honeycreeper_nodes.csv').map(n => {
  const o = {};
  Object.keys(n).forEach(k => { o[k] = n[k] === '' ? null : n[k]; });
  o.declared_extinct_2023 = n.declared_extinct_2023 === 'true';
  return o;
});
const edges = read('honeycreeper_edges.csv').map(e => {
  const o = {};
  Object.keys(e).forEach(k => { o[k] = e[k] === '' ? null : e[k]; });
  return o;
});
const pop = {};
read('honeycreeper_pop.csv').forEach(r => {
  pop[r.key] = {
    anchors: r.anchors.split(';').map(a => { const p = a.split(':'); return [parseInt(p[0], 10), parseFloat(p[1])]; }),
    surveys: r.survey_years ? r.survey_years.split(';').map(s => parseInt(s, 10)) : [],
    confidence: r.confidence, note: r.source_note
  };
});

// ---- validation ----
const keys = new Set(nodes.map(n => n.key));
const parent = {}, kids = {}, nodeT = {};
edges.forEach(e => {
  if (parent[e.child_key]) throw new Error('two parents for ' + e.child_key);
  parent[e.child_key] = e.parent_key;
  (kids[e.parent_key] = kids[e.parent_key] || []).push(e.child_key);
  const t = parseFloat(e.divergence_mya);
  if (nodeT[e.parent_key] != null && Math.abs(nodeT[e.parent_key] - t) > 1e-9) throw new Error('sibling times differ under ' + e.parent_key);
  nodeT[e.parent_key] = t;
});
nodes.forEach(n => { if (!parent[n.key]) throw new Error('species not in tree: ' + n.key); });
Object.keys(pop).forEach(k => { if (!keys.has(k)) throw new Error('pop row for unknown species ' + k); });
nodes.filter(n => n.display_status === 'extant').forEach(n => { if (!pop[n.key]) throw new Error('extant species without pop anchors: ' + n.key); });
Object.keys(kids).forEach(p => kids[p].forEach(c => { if (nodeT[c] != null && nodeT[c] > nodeT[p] + 1e-9) throw new Error('child older than parent: ' + c); }));
const leafCount = nodes.length, internal = Object.keys(kids).filter(k => !keys.has(k)).length;

const out = '// honeycreeper_data.js — GENERATED by gen_data.js from honeycreeper_nodes.csv + honeycreeper_edges.csv + honeycreeper_pop.csv. Do not edit by hand.\n' +
  'const HC_NODES = ' + JSON.stringify(nodes, null, 1) + ';\n' +
  '// Nested tree: one row per edge; divergence_mya = the PARENT node\'s split time (all siblings share it). child_label names internal nodes.\n' +
  'const HC_EDGES = ' + JSON.stringify(edges, null, 1) + ';\n' +
  '// Population anchors [year, birds] per extant species (log-interpolated); confidence = measured | approx.\n' +
  'const HC_POP = ' + JSON.stringify(pop, null, 1) + ';\n';
fs.writeFileSync(path.join(__dirname, 'honeycreeper_data.js'), out, 'utf8');
console.log('OK species=' + leafCount + ' internal nodes=' + internal + ' edges=' + edges.length + ' pop rows=' + Object.keys(pop).length);
